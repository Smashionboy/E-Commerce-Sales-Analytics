"""Generate findings from computed values, never manually maintained KPI literals."""

import pandas as pd


def business_report(
    kpis: dict,
    monthly: pd.DataFrame,
    categories: pd.DataFrame,
    customers: pd.DataFrame,
    segments: pd.DataFrame,
    sequence: pd.DataFrame,
    stats: dict,
    sales: pd.DataFrame,
    quality: pd.DataFrame,
    snapshot: pd.Timestamp,
) -> str:
    """Produce a Russian business note with observations, actions and limitations."""
    if sales.empty:
        return "# Результаты анализа\n\nАналитическая выборка пуста. Выводы не сформированы.\n"
    repeat = (customers.frequency >= 2).sum()
    share = repeat / len(customers) * 100
    top = categories.iloc[0]
    total_gmv = kpis["product_gmv_brl"]
    top5 = (
        f"{categories.head(5).revenue.sum() / total_gmv * 100:.2f}%"
        if total_gmv
        else "не определена при нулевом GMV"
    )
    top_share = (
        f"{top['revenue'] / total_gmv:.2%} GMV"
        if total_gmv
        else "доля не определена при нулевом GMV"
    )
    valid = sales.loc[sales.delivery_days >= 0]
    late = valid.is_late.mean() * 100
    peak = monthly.loc[monthly.revenue.idxmax()]
    median = sales.revenue.median()
    p99 = sales.revenue.quantile(0.99)
    p = stats.get("p_value")
    ptext = (
        "не рассчитан"
        if p is None
        else ("< 1e-300 (численное округление до 0)" if p == 0 else f"{p:.3g}")
    )
    stext = "Недостаточно наблюдений для теста."
    if stats["status"] == "ok":
        lo, hi = stats["mean_difference_ci95"]
        stext = f"""H0: распределения оценок одинаковы у доставленных вовремя и с задержкой заказов.
H1: распределения различаются (двусторонняя проверка, α=0,05).
Выбран Mann–Whitney U с поправкой на связанные ранги: оценки порядковые, имеют пять значений.
В тесте {stats["n_late"]:,} заказов с задержкой и {stats["n_on_time"]:,} без задержки;
использован первый подходящий заказ каждого `customer_unique_id`, ответ на отзыв — после получения.
U = {stats["u_statistic"]:,.0f}, p-value {ptext};
ранговая бисериальная корреляция (late − on time) = {stats["rank_biserial"]:.3f}.
Средняя оценка: {stats["mean_late"]:.2f} против {stats["mean_on_time"]:.2f};
медиана: {stats["median_late"]:.0f} против {stats["median_on_time"]:.0f}.
Описательная разность средних {stats["mean_difference"]:.2f}, bootstrap 95% ДИ [{lo:.2f}; {hi:.2f}]
({stats["bootstrap_resamples"]} повторов, seed {stats["seed"]}).
Доля оценок 1–2: {stats["low_score_rate_late"]:.1%} против {stats["low_score_rate_on_time"]:.1%}.
При α=0,05 {"отвергаем" if p < 0.05 else "не отвергаем"} H0.
U не является чистым тестом разности медиан; разность средних приведена отдельно для масштаба.
Наблюдения независимы лишь приближённо: остаются общие продавцы, регионы, сезонность.
Это связь, причинное влияние задержки не установлено; отзыв отражает и другие стороны заказа."""
    sensitivity = pd.DataFrame(stats["sensitivity_including_pre_receipt_reviews"])
    sensitivity_text = (
        sensitivity.round(3).to_markdown(index=False)
        if len(sensitivity)
        else "Нет наблюдений."
    )
    return f"""# E-Commerce Sales Analytics: бизнес-результаты

Источник: реальные данные Olist, Kaggle. Валюта — бразильский реал (BRL), номинальные суммы.
Задача: описать продажи, повторные покупки и связь доставки с оценкой, определить направления проверки бизнес-гипотез.

## Выборка и KPI

Доставленные (`delivered`) заказы с позициями, даты покупки
{sales.order_purchase_timestamp.min():%d.%m.%Y}–{sales.order_purchase_timestamp.max():%d.%m.%Y}.
Snapshot RFM: {snapshot:%d.%m.%Y}, день после последней покупки во всей исходной таблице заказов.

| Показатель | Значение |
|---|---:|
| Товарный GMV без доставки | {kpis["product_gmv_brl"]:,.2f} BRL |
| Доставленные заказы | {kpis["orders"]:,} |
| Средний чек без доставки | {kpis["aov_brl"]:,.2f} BRL |
| Среднее число позиций | {kpis["mean_items_per_order"]:.3f} |
| Уникальные покупатели | {kpis["customers"]:,} |
| Покупатели с ≥2 заказами | {repeat:,} ({share:.2f}%) |

GMV — сумма `order_items.price`, это стоимость товаров, а не комиссия или прибыль Olist.
Уникальная покупка — один `order_id`; покупатель — `customer_unique_id`, поскольку `customer_id` меняется между заказами.
Отменённые, недоступные и ещё не доставленные заказы исключены. Статус относится к финальному снимку.
Доставка и платежи не используются для подмены товарного GMV. Возвраты и фактический доход продавца не известны.

## Наблюдения и практические действия

1. В среднем {kpis["mean_items_per_order"]:.2f} позиции на заказ. Проверить совместно покупаемые категории
   и возможность комплектов; сначала оценить покрытие и маржинальность, которых здесь нет.
2. Медиана стоимости заказа {median:.2f} BRL против среднего {kpis["aov_brl"]:.2f} BRL;
   P99 = {p99:.2f} BRL. Для мониторинга корзины показывать медиану и перцентили вместе со средним;
   дорогие заказы не удалять автоматически как ошибки.
3. Категория `{top["category"]}` даёт {top["revenue"]:,.2f} BRL ({top_share}).
   Первые пять категорий дают {top5}. Начать проверку ассортимента и сервиса с этих категорий;
   высокий оборот сам по себе не означает высокую прибыль.
4. Только {share:.2f}% покупателей совершили повторный доставленный заказ в наблюдаемом окне.
   Проверить повторные покупки по когортам и длине наблюдения до оценки удержания; это не оценка пожизненного оттока.
5. Пик GMV приходится на {peak["month"]:%Y-%m}: {peak["revenue"]:,.2f} BRL,
   {int(peak["orders"]):,} заказов. Для планирования нагрузки исследовать этот период подробнее;
   причина пика без календаря кампаний не установлена. Крайние месяцы и конец периода могут быть неполными.
6. Среди {len(valid):,} доставленных заказов с неотрицательным сроком и известной датой получения
   доля получения позже обещанного календарного дня — {late:.2f}%,
   медианный срок — {valid.delivery_days.median():.2f} дня.
   Проверить обещанные сроки по маршрутам и продавцам, прежде чем менять SLA.
7. RFM-сегменты описывают наблюдаемые R/F/M; таблица ниже показывает их масштаб.
   В условиях редких повторов F задан как 1/2/3+, R и M — три уровня по процентильным рангам.
   Сегменты можно использовать для пилотного эксперимента коммуникаций с контрольной группой.

## Сравнение сегментов

{segments.round(2).to_markdown(index=False)}

## Первый и повторный заказ

{sequence.groupby("buyer_type").agg(orders=("order_id", "size"), gmv_brl=("revenue", "sum"), aov_brl=("revenue", "mean")).round(2).to_markdown()}

Это описательное сравнение, не тест причинного эффекта повторной покупки.

## Доставка и отзывы: одна заранее выбранная гипотеза

{stext}

Чувствительность к исключению отзывов до получения (первый подходящий заказ клиента,
включены все известные оценки при валидной доставке; дополнительный p-value не рассчитывается):

{sensitivity_text}

`is_late=True` — задержка. Исключение отзывов до получения особенно заметно для задержанных заказов:
такой отзыв мог описывать неполученный товар. Основной тест относится к отзывам после получения,
а не ко всем заказам; переносить его размер эффекта на всю базу нельзя.

## Качество данных и принятые решения

{quality.to_markdown(index=False)}

Пустые тексты отзывов не означают отсутствие оценки. Пустые характеристики товаров и отсутствующие
категории не заполняются средними; для категорий используется `unknown`, а при отсутствии перевода — исходное имя.
Отсутствующие даты доставки не восстанавливаются: заказ входит в продажи, но не в анализ длительности/задержки.
Если отзывов несколько, выбран последний по времени ответа с детерминированным разрешением совпадений.
Отзыв до получения исключается из статистической выборки. Денежные расхождения с платежами остаются диагностикой.
Число категорийных заказов не аддитивно: заказ может содержать несколько категорий.

## Ограничения

- Наблюдательный срез одной платформы Бразилии 2016–2018 гг.; результаты не отражают текущий рынок.
- Конец окна цензурирован: недавние покупки могли ещё не стать доставленными; месячный спад не доказывает падение спроса.
- RFM рассчитан ретроспективно по финальным статусам, это не историческая модель, обученная на информации на дату покупки.
- Повторные покупки за пределами платформы и окна не видны; F — число заказов, не число дней покупки.
- Нет себестоимости, комиссий, возвратов, маркетинговых затрат и налогов; прибыль и ROI не рассчитываются.
- Оценки оставляют не все клиенты. Последний отзыв — обоснованное правило агрегации, но оно влияет на выборку.
- Даты исходные, без часового пояса; для задержки сравниваются календарные дни. Ничего не конвертируется в UTC.
- Bootstrap ДИ и p-value не учитывают кластеризацию продавцов и маршрутов; вывод требует проверки устойчивости.
- Рекомендации — направления проверки, а не обещание роста продаж.

Все значения сформированы `python -m src.run_analysis`. Подробные таблицы — `reports/*.csv`,
полный профиль исходных таблиц — `reports/data_profile.json`; воспроизводимость источника — `reports/source_manifest.json`.
"""
